"""Airport weather stations (ASOS/AWOS) used to calibrate reanalysis wind.

Source: Iowa Environmental Mesonet station networks, https://mesonet.agron.iastate.edu/
Writes data/stations.js: window.WE_STATIONS = [[id, name, lat, lon, first_year, is_awos], ...]
"""
import json
from pathlib import Path

import requests

NETWORKS = ["TX_ASOS", "NM_ASOS", "OK_ASOS", "LA_ASOS", "AR_ASOS"]
OUT = Path(__file__).parent.parent / "data" / "stations.js"


def main():
    rows = []
    for net in NETWORKS:
        j = requests.get(f"https://mesonet.agron.iastate.edu/geojson/network/{net}.geojson", timeout=60).json()
        for f in j["features"]:
            p = f["properties"]
            if not p.get("online") or p.get("archive_end"):
                continue
            lon, lat = f["geometry"]["coordinates"][:2]
            begin = int((p.get("archive_begin") or "2100")[:4])
            awos = 1 if (p.get("attributes") or {}).get("IS_AWOS") == "1" else 0
            name = (p.get("sname") or p["sid"]).replace("_", " ").title().replace("Arpt", "Airport").replace(" Apt", " Airport")
            rows.append([p["sid"], f"{name}, {p.get('state', '')}", round(lat, 4), round(lon, 4), begin, awos])
    js = "/* generated by tools/fetch_stations.py (Iowa Environmental Mesonet) */\nwindow.WE_STATIONS = " + \
         json.dumps(rows, separators=(",", ":")) + ";\n"
    OUT.write_text(js, encoding="utf-8")
    print(len(rows), "stations,", len(js) // 1024, "KB")


if __name__ == "__main__":
    main()
